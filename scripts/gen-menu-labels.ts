// Regenerates supabase/functions/_shared/menuLabels.ts from src/data/menuData.ts.
// Run: bun scripts/gen-menu-labels.ts
import { writeFileSync } from "fs";
import { getProteins, getVegetarianEntrees, LEGACY_MENU_ALIASES, resolveMenuLabel } from "../src/data/menuData";

export function buildMenuLabels(): Record<string, string> {
  const ids = new Set<string>([
    ...getProteins("regular").map((p) => p.id), ...getProteins("wedding").map((p) => p.id),
    ...getVegetarianEntrees("regular").map((v: { id: string }) => v.id), ...Object.keys(LEGACY_MENU_ALIASES),
  ]);
  return Object.fromEntries([...ids].sort().map((id) => [id, resolveMenuLabel(id)]));
}

if (import.meta.main) {
  const body = `// GENERATED by scripts/gen-menu-labels.ts from src/data/menuData.ts - do not edit by hand.
// Documents (emails, invoices) use these names so they match the website and forms.
export const MENU_LABELS: Record<string, string> = ${JSON.stringify(buildMenuLabels(), null, 2)};

const titleCase = (id: string) => id.split(/[-_\\s]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase()).join(' ');

/** Canonical display name for a stored menu id; unknown ids fall back to title case. */
export const labelMenuItem = (id: string): string => (id ? MENU_LABELS[id] ?? titleCase(id) : '');
`;
  writeFileSync("supabase/functions/_shared/menuLabels.ts", body);
}
